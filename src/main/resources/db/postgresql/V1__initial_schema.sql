CREATE TABLE users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, username VARCHAR(60) NOT NULL UNIQUE,
 password_hash VARCHAR(100) NOT NULL, role VARCHAR(10) NOT NULL DEFAULT 'ADMIN',
 employee_id VARCHAR(30) UNIQUE, password_version INT NOT NULL DEFAULT 0,
 CONSTRAINT chk_users_role_link CHECK ((role = 'ADMIN' AND employee_id IS NULL) OR (role = 'EMPLOYEE' AND employee_id IS NOT NULL)),
 active BOOLEAN NOT NULL DEFAULT TRUE, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE employees (
 employee_id VARCHAR(30) PRIMARY KEY, full_name VARCHAR(120) NOT NULL, position VARCHAR(80),
 contact_number VARCHAR(30), address VARCHAR(300), active BOOLEAN NOT NULL DEFAULT TRUE,
 sensor_slot_id INT UNIQUE, daily_rate DECIMAL(10,2) NOT NULL DEFAULT 0.00,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE schedules (
 employee_id VARCHAR(30) PRIMARY KEY, working_days VARCHAR(40) NOT NULL,
 expected_time_in TIME NOT NULL, expected_time_out TIME NOT NULL, grace_minutes INT NOT NULL DEFAULT 5,
 min_scan_gap_seconds INT NOT NULL DEFAULT 60,
 CONSTRAINT fk_schedule_employee FOREIGN KEY(employee_id) REFERENCES employees(employee_id) ON UPDATE CASCADE ON DELETE CASCADE,
 CHECK(grace_minutes>=0), CHECK(min_scan_gap_seconds>=0)
);
CREATE TABLE absences (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, employee_id VARCHAR(30) NOT NULL, absence_date DATE NOT NULL,
 reason VARCHAR(20) NOT NULL CHECK(reason IN ('Sick','Emergency','Leave','Unexcused')),
 notes VARCHAR(500), recorded_by VARCHAR(60) NOT NULL,
 CONSTRAINT uq_absence_day UNIQUE (employee_id,absence_date),
 CONSTRAINT fk_absence_employee FOREIGN KEY(employee_id) REFERENCES employees(employee_id) ON UPDATE CASCADE ON DELETE RESTRICT
);
CREATE TABLE attendance (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, employee_id VARCHAR(30) NOT NULL, attendance_date DATE NOT NULL,
 time_in TIMESTAMP, time_out TIMESTAMP, status VARCHAR(20) NOT NULL,
 late_minutes INT NOT NULL DEFAULT 0, hours_worked DECIMAL(6,2) NOT NULL DEFAULT 0.00,
 scan_uuid VARCHAR(36) UNIQUE, CONSTRAINT uq_attendance_day UNIQUE (employee_id,attendance_date),
 CONSTRAINT fk_attendance_employee FOREIGN KEY(employee_id) REFERENCES employees(employee_id) ON UPDATE CASCADE ON DELETE RESTRICT
);
CREATE TABLE scan_events (
 scan_uuid VARCHAR(36) PRIMARY KEY, sensor_slot_id INT NOT NULL, scanned_at TIMESTAMP NOT NULL,
 outcome VARCHAR(20) NOT NULL, employee_id VARCHAR(30),
 CONSTRAINT fk_scan_employee FOREIGN KEY(employee_id) REFERENCES employees(employee_id) ON UPDATE CASCADE ON DELETE SET NULL
);
CREATE TABLE device_commands (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, type VARCHAR(20) NOT NULL, employee_id VARCHAR(30) NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'PENDING', created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 result_message VARCHAR(300),
 CONSTRAINT fk_command_employee FOREIGN KEY(employee_id) REFERENCES employees(employee_id) ON UPDATE CASCADE ON DELETE RESTRICT
);
CREATE TABLE devices (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(80) NOT NULL UNIQUE, api_key_hash VARCHAR(64) NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'OFFLINE', last_seen TIMESTAMP
);
CREATE TABLE payroll_settings (
 employee_id VARCHAR(30) PRIMARY KEY, daily_rate DECIMAL(10,2) NOT NULL DEFAULT 0.00,
 hourly_mode BOOLEAN NOT NULL DEFAULT FALSE,
 CONSTRAINT fk_payroll_employee FOREIGN KEY(employee_id) REFERENCES employees(employee_id) ON UPDATE CASCADE ON DELETE CASCADE
);
CREATE TABLE payroll_records (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, employee_id VARCHAR(30) NOT NULL, period_start DATE NOT NULL,
 period_end DATE NOT NULL, days_present INT NOT NULL, daily_rate_snapshot DECIMAL(10,2) NOT NULL DEFAULT 0.00, days_absent INT NOT NULL, late_minutes INT NOT NULL DEFAULT 0,
 undertime_minutes INT NOT NULL DEFAULT 0, gross_pay DECIMAL(10,2) NOT NULL, deductions DECIMAL(10,2) NOT NULL,
 late_deduction DECIMAL(10,2) NOT NULL DEFAULT 0.00,
 other_deductions DECIMAL(10,2) NOT NULL DEFAULT 0.00, policy_snapshot TEXT,
 net_pay DECIMAL(10,2) NOT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT uq_payroll_period UNIQUE (employee_id,period_start,period_end),
 CONSTRAINT fk_payroll_record_employee FOREIGN KEY(employee_id) REFERENCES employees(employee_id) ON UPDATE CASCADE ON DELETE RESTRICT,
 CHECK(period_end>=period_start)
);
CREATE TABLE unregistered_scans (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, scan_uuid VARCHAR(36) NOT NULL UNIQUE, sensor_slot_id INT NOT NULL,
 scanned_at TIMESTAMP NOT NULL
);
CREATE TABLE audit_logs (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, actor_username VARCHAR(60) NOT NULL, action VARCHAR(60) NOT NULL,
 entity_name VARCHAR(60) NOT NULL, entity_id VARCHAR(80) NOT NULL, before_json JSON, after_json JSON,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE users ADD CONSTRAINT fk_users_employee
    FOREIGN KEY (employee_id) REFERENCES employees(employee_id) ON UPDATE CASCADE ON DELETE RESTRICT;

CREATE TABLE deduction_policies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    effective_date DATE NOT NULL UNIQUE,
    rate_per_minute DECIMAL(10,4) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    created_by VARCHAR(60) NOT NULL
);

CREATE UNIQUE INDEX uq_users_username_ci ON users (lower(username));
CREATE INDEX idx_employee_name ON employees (full_name);
CREATE INDEX idx_employee_active ON employees (active);
CREATE INDEX idx_absence_date ON absences (absence_date);
CREATE INDEX idx_attendance_date ON attendance (attendance_date);
CREATE INDEX idx_attendance_employee_date ON attendance (employee_id,attendance_date);
CREATE INDEX idx_scan_time ON scan_events (scanned_at);
CREATE INDEX idx_command_status ON device_commands (status,created_at);
CREATE INDEX idx_device_status ON devices (status,last_seen);
CREATE INDEX idx_unregistered_time ON unregistered_scans (scanned_at);
CREATE INDEX idx_audit_entity ON audit_logs (entity_name,entity_id);
CREATE INDEX idx_audit_time ON audit_logs (created_at);
